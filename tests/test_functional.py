"""Functional tests - the API-compatibility evidence.

THIS IS THE MOST IMPORTANT FILE IN THE REPOSITORY.

The Lightwell claim is that a backported fix lands in the exact version you
already run, with the API unchanged and no code migration. The only honest proof
of that claim is an unchanged test suite passing before and after. Not a
scanner, not a version string on a slide - this.

So: do not edit this file between Act 2 and Act 4. If you need to change it to
make Act 4 pass, the remediation broke something and that is a finding worth
more than the demo.

Tests requiring a database are skipped automatically when one is not reachable,
so the suite is still useful on a laptop.
"""
import pytest
from fastapi.testclient import TestClient

from app import db
from app.main import app

client = TestClient(app)

needs_db = pytest.mark.skipif(
    not db.health()["available"],
    reason="No database reachable; set IM_TRAIN_DB_URL to run these",
)


# --------------------------------------------------------------------------- #
# No database required
# --------------------------------------------------------------------------- #

def test_healthz():
    res = client.get("/api/healthz")
    assert res.status_code == 200
    assert res.json()["status"] == "ok"


def test_status_shape():
    """The Status page contract. The demo is filmed around these keys."""
    res = client.get("/api/status")
    assert res.status_code == 200
    body = res.json()

    for key in ("tier", "hostname", "os_version", "arch", "image", "digest",
                "rollback_available", "dependencies", "lightwell", "database",
                "probe"):
        assert key in body, f"missing key: {key}"

    assert "jinja2" in body["dependencies"]
    assert body["lightwell"]["package"] == "jinja2"
    assert isinstance(body["lightwell"]["remediated"], bool)


def test_index_serves_ui():
    res = client.get("/")
    assert res.status_code == 200
    assert "Image Mode Train Service" in res.text


def test_receipt_renders_default_template():
    """Rendering must keep working after remediation - that is the point."""
    from app import receipts

    booking = {
        "reference": "IMT-4100",
        "passenger_name": "D. Chugtai",
        "service_code": "EC 220",
        "origin_name": "Ostrava Hlavni",
        "destination_name": "Praha Hlavni",
        "travel_date": "2026-10-01",
        "depart_time": "06:12:00",
        "price_eur": 28.5,
    }
    out = receipts.render_receipt(None, booking)
    assert "IMT-4100" in out
    assert "Ostrava Hlavni" in out
    assert "28.50" in out


