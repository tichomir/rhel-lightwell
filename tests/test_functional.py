@needs_db
def test_stations_listed():
    res = client.get("/api/stations")
    assert res.status_code == 200
    codes = {s["code"] for s in res.json()}
    assert {"OSR", "PRG", "VIE"} <= codes


@needs_db
def test_search_returns_services():
    res = client.post("/api/search", json={
        "origin": "OSR", "destination": "PRG", "travel_date": "2026-10-01",
    })
    assert res.status_code == 200
    rows = res.json()
    assert len(rows) >= 1
    assert all(r["origin_name"] == "Ostrava Hlavni" for r in rows)


@needs_db
def test_search_rejects_same_station():
    res = client.post("/api/search", json={
        "origin": "OSR", "destination": "OSR", "travel_date": "2026-10-01",
    })
    assert res.status_code == 400


@needs_db
def test_book_then_retrieve():
    services = client.post("/api/search", json={
        "origin": "OSR", "destination": "PRG", "travel_date": "2026-10-01",
    }).json()

    created = client.post("/api/bookings", json={
        "service_id": services[0]["id"],
        "travel_date": "2026-10-01",
        "passenger_name": "Integration Test",
    })
    assert created.status_code == 200
    reference = created.json()["reference"]
    assert reference.startswith("IMT-")

    listed = client.get("/api/bookings").json()
    assert reference in {b["reference"] for b in listed}


@needs_db
def test_receipt_preview_for_real_booking():
    bookings = client.get("/api/bookings").json()
    assert bookings, "seed data missing; run sql/seed.sql"

    res = client.post("/api/receipt/preview", json={"booking_id": bookings[0]["id"]})
    assert res.status_code == 200
    assert bookings[0]["reference"] in res.json()["receipt"]


@needs_db
def test_receipt_preview_unknown_booking():
    res = client.post("/api/receipt/preview", json={"booking_id": 999999})
    assert res.status_code == 404


@needs_db
def test_seed_booking_survives():
    """Referenced in Act 4: /var persisted across the image upgrade.

    The seeded booking must still be present after bootc upgrade and reboot.
    """
    listed = client.get("/api/bookings").json()
